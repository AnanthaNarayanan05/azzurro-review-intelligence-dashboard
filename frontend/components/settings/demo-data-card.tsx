"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { FlaskConical } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";

import { ErrorState } from "@/components/states/error-state";
import {
  AlertDialog,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { useHydrated } from "@/hooks/use-hydrated";
import { propertiesQueryKey } from "@/hooks/use-properties";
import { getDemoStatus, loadDemoData, removeDemoData } from "@/services/imports";

export function DemoDataCard() {
  const hydrated = useHydrated();
  const queryClient = useQueryClient();
  const [confirmRemove, setConfirmRemove] = useState(false);
  const status = useQuery({ queryKey: ["demo"], queryFn: getDemoStatus });

  const refresh = () => {
    void queryClient.invalidateQueries({ queryKey: ["demo"] });
    void queryClient.invalidateQueries({ queryKey: ["analysis"] });
    void queryClient.invalidateQueries({ queryKey: ["imports"] });
    void queryClient.invalidateQueries({ queryKey: propertiesQueryKey });
  };

  const load = useMutation({
    mutationFn: loadDemoData,
    onSuccess: (report) => {
      toast.success(`Loaded ${report.imported_rows.toLocaleString()} synthetic demo reviews.`);
      refresh();
    },
    onError: (error: Error) => toast.error(error.message),
  });

  const remove = useMutation({
    mutationFn: removeDemoData,
    onSuccess: (result) => {
      toast.success(`Removed ${result.removed_reviews.toLocaleString()} synthetic reviews.`);
      setConfirmRemove(false);
      refresh();
    },
    onError: (error: Error) => toast.error(error.message),
  });

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <FlaskConical className="size-4" aria-hidden /> Demo data
          {status.data?.loaded && <Badge variant="outline">Loaded</Badge>}
        </CardTitle>
        <CardDescription>
          Invented reviews for trying the dashboard when you have no real export. They are generated by a script, are
          labelled synthetic everywhere, and never claim to come from Booking.com.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-3">
        {!hydrated || status.isPending ? (
          <Skeleton className="h-10 w-64" />
        ) : status.isError ? (
          <ErrorState title="Could not check demo data" message={status.error.message} onRetry={() => status.refetch()} />
        ) : (
          <>
            <p className="text-sm text-muted-foreground">
              {status.data.loaded
                ? `${status.data.synthetic_review_count.toLocaleString()} synthetic reviews are currently stored.`
                : "No demo data is loaded."}
            </p>
            {status.data.loaded ? (
              <Button variant="outline" onClick={() => setConfirmRemove(true)} disabled={remove.isPending}>
                Remove demo data
              </Button>
            ) : (
              <Button onClick={() => load.mutate()} disabled={load.isPending}>
                {load.isPending ? "Generating and importing…" : "Load demo data"}
              </Button>
            )}
          </>
        )}
      </CardContent>

      <AlertDialog open={confirmRemove} onOpenChange={(open) => !remove.isPending && setConfirmRemove(open)}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Remove all demo data?</AlertDialogTitle>
            <AlertDialogDescription>
              This deletes every synthetic review and its import record. Genuine imported reviews and your properties
              are not touched. This cannot be undone, but the demo data can be loaded again.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={remove.isPending}>Keep demo data</AlertDialogCancel>
            <Button variant="destructive" onClick={() => remove.mutate()} disabled={remove.isPending}>
              {remove.isPending ? "Removing…" : "Remove demo data"}
            </Button>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </Card>
  );
}
